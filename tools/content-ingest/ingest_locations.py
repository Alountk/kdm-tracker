from kotlin_emit import _chunk_for_wrapping, indent, kotlin_escape, normalize_ws  # noqa: E402
from pdf_text import _require, pdf_info, pdf_text  # noqa: E402

FORM_FEED = "\f"
GENERATED_HEADER = "// Generated by tools/content-ingest/ingest_locations.py. Do not edit by hand."

DEFAULT_LOCATIONS_IDENTITY = Path("tools/content-ingest/identity/locations.csv")


DEFAULT_RESOURCES_IDENTITY = Path("tools/content-ingest/identity/resources.csv")

# The localized display names of every action this emitter produces, keyed by the name printed on
# the card. An action the table does not cover aborts the run rather than emitting a name only one
# language can render.
ACTION_NAMES: Dict[str, Tuple[str, str]] = {
    "Innovar": ("Innovar", "Innovate"),
}

# Card resource token -> canonical name in generated Core15Resources.kt. The
# canonical names are the full Spanish card names ("Hueso de Monstruo", …); a
# token with no card (e.g. "restos") is kept verbatim and flagged in the README.
RESOURCE_ALIASES: Dict[str, str] = {
    "hueso": "Hueso de Monstruo",
    "piel": "Piel de Monstruo",
    "órgano": "Órgano de Monstruo",
    "calavera": "Calavera",
    "hierro": "Hierro",
    "cuero": "Cuero",
}

COST_RE = re.compile(r"^(\d+)\s*x\s*(.+)$", re.IGNORECASE)
CONSTRUIR_RE = re.compile(r"^construir\b(.*)$", re.IGNORECASE)
LOCALIZACION_RE = re.compile(r"^localización de asentamiento$", re.IGNORECASE)
LOCALIZACION_SUFFIX_RE = re.compile(r"\s*localización de asentamiento\s*$", re.IGNORECASE)


@dataclass
class SettlementAction:
    name: str
    kind: str = "ENDEAVOR"
    endeavor_cost: int = 1
    resource_cost: Dict[str, int] = field(default_factory=dict)
    once_per_phase: bool = False
    draw: int = 0
    keep: int = 0
    effect: str = ""


@dataclass
class SettlementLocation:
    name: str
    requires: Tuple[str, ...] = ()
    build_endeavors: int = 0
    build_cost: Dict[str, int] = field(default_factory=dict)
    actions: Tuple[SettlementAction, ...] = ()


@dataclass
class BuildOffer:
    target: str
    cost: Dict[str, int]


def body_lines(text: str) -> List[str]:
    """The card's non-blank, stripped lines, in order."""
    return [line.strip() for line in text.splitlines() if line.strip()]


def resolve_resource(token: str) -> str:
    stripped = token.strip().lower()
    return RESOURCE_ALIASES.get(stripped, stripped)


def parse_cost(text: str) -> Dict[str, int]:
    """Parse ``"3 x hueso, 1 x piel"`` (or the ``-raw`` ``"3xhueso"`` form) to name → count."""
    cost: Dict[str, int] = {}
    for segment in re.split(r"[,\n]", text):
        segment = segment.strip()
        if not segment:
            continue
        match = COST_RE.match(segment)
        count, token = (int(match.group(1)), match.group(2)) if match else (1, segment)
        name = resolve_resource(token)
        cost[name] = cost.get(name, 0) + count
    return cost


def parse_build_targets(lines: Sequence[str]) -> List[Tuple[str, int]]:
    """The ``(target, line index)`` of every ``Construir <target>`` block on a card."""
    targets: List[Tuple[str, int]] = []
    for index, line in enumerate(lines):
        match = CONSTRUIR_RE.match(line)
        if match is None:
            continue
        target = match.group(1).strip()
        if not target and index + 1 < len(lines):
            target = lines[index + 1]
        target = LOCALIZACION_SUFFIX_RE.sub("", target).strip()
        if target:
            targets.append((target, index))
    return targets


def raw_adjacent_cost(raw_page: str, target: str) -> Optional[Dict[str, int]]:
    """Cost tokens bound to ``target`` in the ``-raw`` order, or None if not adjacent.

    An empty dict is a real "no cost" answer (the Lantern Hoard's tier-1 bars);
    ``None`` means the target name is not adjacent to ``Construir`` in the raw
    stream, so the caller must fall back to the default order.
    """
    pattern = re.compile(
        r"(?:construir\s+" + re.escape(target) + r"\b|" + re.escape(target) + r"\s+construir\b)",
        re.IGNORECASE,
    )
    match = pattern.search(raw_page)
    if match is None:
        return None

    tokens = raw_page[: match.start()].split()
    collected: List[str] = []
    for token in reversed(tokens):
        if COST_RE.match(token):
            collected.append(token)
        else:
            break

    cost: Dict[str, int] = {}
    for token in reversed(collected):
        for name, count in parse_cost(token).items():
            cost[name] = cost.get(name, 0) + count
    return cost


def default_build_cost(lines: Sequence[str], target_index: int) -> Dict[str, int]:
    """The cost box after the block's ``Localización de Asentamiento`` caption."""
    localization_index: Optional[int] = None
    for index in range(target_index + 1, len(lines)):
        if CONSTRUIR_RE.match(lines[index]):
            break
        if LOCALIZACION_RE.match(lines[index]):
            localization_index = index
            break
    if localization_index is None:
        return {}

    cost: Dict[str, int] = {}
    for index in range(localization_index + 1, len(lines)):
        if CONSTRUIR_RE.match(lines[index]):
            break
        if COST_RE.match(lines[index]):
            for name, count in parse_cost(lines[index]).items():
                cost[name] = cost.get(name, 0) + count
    return cost


def parse_builds(lines: Sequence[str], raw_page: str, source: str) -> List[BuildOffer]:
    """Every build block on a card, as ``target`` → cost.

    ``source`` is the building card's name; it is carried by the caller into
    ``SettlementLocation.requires``.
    """
    offers: List[BuildOffer] = []
    for target, index in parse_build_targets(lines):
        cost = raw_adjacent_cost(raw_page, target)
        if cost is None:
            cost = default_build_cost(lines, index)
        offers.append(BuildOffer(target=target, cost=cost))
    return offers


def parse_actions(lines: Sequence[str]) -> List[SettlementAction]:
    """The card's ``Esfuerzo`` action(s); today only the Lantern Hoard's Innovate."""
    esfuerzo = next((i for i, line in enumerate(lines) if line.lower() == "esfuerzo"), None)
    if esfuerzo is None:
        return []

    resource_cost: Dict[str, int] = {}
    cursor = esfuerzo + 1
    while cursor < len(lines):
        token = lines[cursor].lower()
        if token not in RESOURCE_ALIASES:
            break
        name = RESOURCE_ALIASES[token]
        resource_cost[name] = resource_cost.get(name, 0) + 1
        cursor += 1

    effect_lines: List[str] = []
    for line in lines[cursor:]:
        if CONSTRUIR_RE.match(line) or line.lower().startswith("requiere"):
            break
        effect_lines.append(line)
    effect = normalize_ws(" ".join(effect_lines))

    draw_match = re.search(r"robar\s+(\d+)\s+cartas", effect, re.IGNORECASE)
    keep_match = re.search(r"qued[aá]os\s+con\s+(\d+)", effect, re.IGNORECASE)

    return [
        SettlementAction(
            name="Innovar",
            kind="INNOVATE",
            endeavor_cost=1,
            resource_cost=resource_cost,
            once_per_phase="una vez por fase" in effect.lower(),
            draw=int(draw_match.group(1)) if draw_match else 0,
            keep=int(keep_match.group(1)) if keep_match else 0,
            effect=effect,
        )
    ]


def parse_card(text: str) -> SettlementLocation:
    """Parse one card page into its own ``SettlementLocation`` (name + actions)."""
    lines = body_lines(text)
    if not lines:
        raise SystemExit("empty card page; refusing to emit a nameless location")
    return SettlementLocation(name=lines[0], actions=tuple(parse_actions(lines)))


def parse_locations(default_text: str, raw_text: str) -> List[SettlementLocation]:
    """Assemble every card plus the build blocks they publish, sorted by name."""
    default_pages = [page for page in default_text.split(FORM_FEED) if page.strip()]
    raw_pages = [page for page in raw_text.split(FORM_FEED) if page.strip()]
    if len(default_pages) != len(raw_pages):
        raise SystemExit(
            f"page split mismatch between the default ({len(default_pages)}) and "
            f"-raw ({len(raw_pages)}) extractions"
        )

    locations: Dict[str, SettlementLocation] = {}
    builds: List[Tuple[str, BuildOffer]] = []
    for default_page, raw_page in zip(default_pages, raw_pages):
        card = parse_card(default_page)
        locations[card.name] = card
        for offer in parse_builds(body_lines(default_page), raw_page, card.name):
            builds.append((card.name, offer))

    for source, offer in builds:
        existing = locations.get(offer.target, SettlementLocation(name=offer.target))
        locations[offer.target] = replace(
            existing,
            build_cost=offer.cost,
            build_endeavors=1,
            requires=tuple(sorted(set(existing.requires) | {source})),
        )

    return sorted(locations.values(), key=lambda location: location.name)


def _inline_map(items: Sequence[Tuple[str, int]], wrapper: Optional[str] = None) -> str:
    def key(name: str) -> str:
        return f'{wrapper}("{kotlin_escape(name)}")' if wrapper else f'"{kotlin_escape(name)}"'

    return "mapOf(" + ", ".join(f"{key(name)} to {value}" for name, value in items) + ")"


def _map_lines(
    key: str,
    base_indent: int,
    mapping: Dict[str, int],
    wrapper: Optional[str] = None,
) -> List[str]:
    inline = f"{indent(base_indent)}{key} = {_inline_map(list(mapping.items()), wrapper)},"
    if len(inline) <= 120:
        return [inline]
    lines = [f"{indent(base_indent)}{key} =", f"{indent(base_indent + 4)}mapOf("]
    for name, value in mapping.items():
        escaped = kotlin_escape(name)
        entry = f'{wrapper}("{escaped}")' if wrapper else f'"{escaped}"'
        lines.append(f"{indent(base_indent + 8)}{entry} to {value},")
    lines.append(f"{indent(base_indent + 4)}),")
    return lines


def _localized_lines(key: str, base_indent: int, es: str, en: str) -> List[str]:
    """A `LocalizedText(es = …, en = …)` assignment, wrapping past 120 columns."""
    if not es:
        raise SystemExit(
            f"identity row for this {key} carries no Spanish name; the Spanish content packs "
            "need one before it can be emitted"
        )
    if not en:
        inline = f'{indent(base_indent)}{key} = LocalizedText(es = "{kotlin_escape(es)}"),'
        if len(inline) <= 120:
            return [inline]
        return [
            f"{indent(base_indent)}{key} =",
            f"{indent(base_indent + 4)}LocalizedText(",
            f'{indent(base_indent + 8)}es = "{kotlin_escape(es)}",',
            f"{indent(base_indent + 4)}),",
        ]
    inline = f'{indent(base_indent)}{key} = LocalizedText(es = "{kotlin_escape(es)}", en = "{kotlin_escape(en)}"),'
    if len(inline) <= 120:
        return [inline]
    return [
        f"{indent(base_indent)}{key} =",
        f"{indent(base_indent + 4)}LocalizedText(",
        f'{indent(base_indent + 8)}es = "{kotlin_escape(es)}",',
        f'{indent(base_indent + 8)}en = "{kotlin_escape(en)}",',
        f"{indent(base_indent + 4)}),",
    ]


def _chunk(escaped: str, budget: int) -> List[str]:
    words = escaped.split(" ")
    chunks: List[List[str]] = []
    current: List[str] = []
    current_len = 0
    for word in words:
        extra = len(word) + (1 if current else 0)
        if current and current_len + extra > budget:
            chunks.append(current)
            current = [word]
            current_len = len(word)
        else:
            current.append(word)
            current_len += extra
    if current:
        chunks.append(current)
    joined = [" ".join(chunk) for chunk in chunks]
    return [chunk + " " for chunk in joined[:-1]] + [joined[-1]]


def _string_lines(key: str, base_indent: int, text: str) -> List[str]:
    escaped = kotlin_escape(text)
    inline = f'{indent(base_indent)}{key} = "{escaped}",'
    if len(inline) <= 120:
        return [inline]

    chunks = _chunk(escaped, 120 - (base_indent + 8) - 4)
    lines = [f"{indent(base_indent)}{key} ="]
    for index, chunk in enumerate(chunks):
        chunk_indent = base_indent + (4 if index == 0 else 8)
        suffix = " +" if index < len(chunks) - 1 else ","
        lines.append(f'{indent(chunk_indent)}"{chunk}"{suffix}')
    return lines


def _action_lines(action: SettlementAction, resource_identity: Dict[str, object]) -> List[str]:
    names = ACTION_NAMES.get(action.name)
    if names is None:
        raise SystemExit(
            f"action {action.name!r} has no entry in ACTION_NAMES; every action needs names in "
            "both languages before it can be emitted"
        )
    lines = [f"{indent(32)}SettlementAction("]
    lines.extend(_localized_lines("names", 36, names[0], names[1]))
    lines.append(f"{indent(36)}kind = ActionKind.{action.kind},")
    lines.append(f"{indent(36)}endeavorCost = {action.endeavor_cost},")
    if action.resource_cost:
        resolved: Dict[str, int] = {}
        for name, count in action.resource_cost.items():
            row = require_row(resource_identity, name, source=f"ingest_locations (action {action.name} cost)")
            resolved[row.resource_id] = count
        lines.extend(_map_lines("resourceCost", 36, resolved, wrapper="ResourceId"))
    if action.once_per_phase:
        lines.append(f"{indent(36)}oncePerPhase = true,")
    if action.draw:
        lines.append(f"{indent(36)}draw = {action.draw},")
    if action.keep:
        lines.append(f"{indent(36)}keep = {action.keep},")
    if action.effect:
        lines.extend(_string_lines("effect", 36, action.effect))
    lines.append(f"{indent(32)}),")
    return lines


def _location_lines(
    location: SettlementLocation,
    location_identity: Dict[str, object],
    resource_identity: Dict[str, object],
) -> List[str]:
    row = require_row(location_identity, location.name, source="ingest_locations")
    lines = [
        f"{indent(20)}SettlementLocation(",
        f'{indent(24)}id = LocationId("{kotlin_escape(row.resource_id)}"),',
    ]
    lines.extend(_localized_lines("names", 24, row.spanish_name or row.english_name, row.english_name))
    if row.description:
        lines.extend(_authored_description_lines(row.description))
    if location.requires:
        requires = "listOf(" + ", ".join(_location_id(name, location_identity) for name in location.requires) + ")"
        entry = f"{indent(24)}requires = {requires},"
        if len(entry) <= 120:
            lines.append(entry)
        else:
            lines.append(f"{indent(24)}requires =")
            lines.append(f"{indent(28)}listOf(")
            lines.extend(f"{indent(32)}{_location_id(name, location_identity)}," for name in location.requires)
            lines.append(f"{indent(28)}),")
    if location.build_endeavors:
        lines.append(f"{indent(24)}buildEndeavors = {location.build_endeavors},")
    if location.build_cost:
        lines.extend(_cost_lines("buildCost", 24, location.build_cost, resource_identity, location.name))
    if location.actions:
        lines.append(f"{indent(24)}actions =")
        lines.append(f"{indent(28)}listOf(")
        for action in location.actions:
            lines.extend(_action_lines(action, resource_identity))
        lines.append(f"{indent(28)}),")
    lines.append(f"{indent(20)}),")
    return lines


def _authored_description_lines(description: str) -> List[str]:
    """`description = LocalizedText(es = …)`, wrapped the way the innovation emitter wraps prose.

    The prose is Spanish-only until the content grows an English column, so the emitted
    `LocalizedText` carries `es` alone and lets `inLanguage` fall back to it.
    """
    escaped = kotlin_escape(description)
    inline = f"{indent(24)}description = LocalizedText(es = \"{escaped}\"),"
    if len(inline) <= 120:
        return [inline]
    chunks = _chunk_for_wrapping(escaped, 68)
    lines = [f"{indent(24)}description =", f"{indent(28)}LocalizedText(", f"{indent(32)}es ="]
    for index, chunk in enumerate(chunks):
        width = 36 if index == 0 else 40
        suffix = " +" if index < len(chunks) - 1 else ","
        lines.append(f'{indent(width)}"{chunk}"{suffix}')
    lines.append(f"{indent(28)}),")
    return lines


def _location_id(name: str, location_identity: Dict[str, object]) -> str:
    row = require_row(location_identity, name, source="ingest_locations (requires)")
    return f'LocationId("{kotlin_escape(row.resource_id)}")'


def _cost_lines(
    key: str,
    base_indent: int,
    cost: Dict[str, int],
    resource_identity: Dict[str, object],
    location_name: str,
) -> List[str]:
    """A resource-cost map keyed by id: every cost name must have an identity row."""
    resolved: Dict[str, int] = {}
    for name, count in cost.items():
        row = require_row(resource_identity, name, source=f"ingest_locations ({location_name} build cost)")
        resolved[row.resource_id] = count
    return _map_lines(key, base_indent, resolved, wrapper="ResourceId")


def emit_kotlin(
    locations: Sequence[SettlementLocation],
    location_identity: Dict[str, object],
    resource_identity: Dict[str, object],
) -> str:
    lines = [
        GENERATED_HEADER,
        "package io.kdmtracker.core.content.generated",
        "",
        "import io.kdmtracker.core.content.ContentBundle",
        "import io.kdmtracker.core.domain.ActionKind",
        "import io.kdmtracker.core.domain.LocalizedText",
        "import io.kdmtracker.core.domain.LocationId",
        "import io.kdmtracker.core.domain.ResourceId",
        "import io.kdmtracker.core.domain.SettlementAction",
        "import io.kdmtracker.core.domain.SettlementLocation",
        "",
        "object Core15Locations {",
        "    val bundle: ContentBundle =",
        "        ContentBundle(",
        "            locations =",
        "                listOf(",
    ]
    for location in locations:
        lines.extend(_location_lines(location, location_identity, resource_identity))
    lines.extend(
        [
            "                ),",
            "        )",
            "}",
        ]
    )
    return "\n".join(lines) + "\n"


DEFAULT_PDF_RELATIVE = Path("external-assets/Juego Completo/Formato XXL 102x204 mm/AF Asentamientos Loc.pdf")
DEFAULT_OUT_RELATIVE = Path("core/src/commonMain/kotlin/io/kdmtracker/core/content/generated/Core15Locations.kt")


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _raw_text(pdf_path: Path) -> str:
    """``pdftotext -raw``: content-stream order, used only to disambiguate overlap."""
    completed = subprocess.run(
        [_require("pdftotext"), "-raw", str(pdf_path), "-"],
        check=True,
        capture_output=True,
        text=True,
        encoding="utf-8",
    )
    return completed.stdout


def main(argv: Optional[Sequence[str]] = None) -> int:
    repo_root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--pdf",
        type=Path,
        default=repo_root / DEFAULT_PDF_RELATIVE,
        help="path to AF Asentamientos Loc.pdf",
    )
    parser.add_argument("--out", type=Path, default=repo_root / DEFAULT_OUT_RELATIVE, help="output Kotlin file")
    args = parser.parse_args(argv)

    if not args.pdf.is_file():
        parser.error(f"PDF not found: {args.pdf}\nPass --pdf <path> (external-assets/ is untracked).")

    default_text = pdf_text(args.pdf, layout=False)
    raw_text = _raw_text(args.pdf)
    declared_pages = pdf_info(args.pdf).get("Pages")
    if declared_pages is not None and default_text.count(FORM_FEED) != int(declared_pages):
        raise SystemExit(
            f"page count mismatch: pdfinfo says {declared_pages}, the text layer has "
            f"{default_text.count(FORM_FEED)} form feeds"
        )

    locations = parse_locations(default_text, raw_text)
    location_identity = load_locations_identity(repo_root / DEFAULT_LOCATIONS_IDENTITY)
    resource_identity = load_identity(repo_root / DEFAULT_RESOURCES_IDENTITY)
    output = emit_kotlin(locations, location_identity, resource_identity)
    unused_rows(location_identity, [location.name for location in locations])

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(output, encoding="utf-8")

    with_actions = sum(1 for location in locations if location.actions)
    buildable = sum(1 for location in locations if location.build_cost or location.requires)
    print(
        f"parsed {len(locations)} locations from {declared_pages} pages "
        f"({buildable} in the build tree, {with_actions} with actions) -> {args.out}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
