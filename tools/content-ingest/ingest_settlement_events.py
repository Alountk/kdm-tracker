#!/usr/bin/env python3
"""Parse the 1.5 settlement-event cards and emit committed Kotlin.

Reads the untracked ``AF Eventos.pdf`` (see ``external-assets/``), extracts one
settlement event per PDF page, and writes a deterministic
``Core15SettlementEvents.kt``.

Design notes
------------
* The PDF renders one card per page, so card boundaries need no guessing: page 1
  is the deck cover and every later page is a card whose second line is the
  ``- evento de asentamiento -`` marker. That marker is validated against the
  exact vocabulary, so a shifted page aborts the run instead of being silently
  mis-read. ``pdfinfo``'s page count is checked against the form-feed split.
* Everything after the marker is the event text.
* Determinism: no timestamps, no paths, entries deduped and sorted by name.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parent))

from kotlin_emit import description_lines, indent, kotlin_escape, normalize_ws  # noqa: E402
from pdf_text import pdf_info, pdf_text  # noqa: E402

FORM_FEED = "\f"
TITLE_PAGE = 1  # 1-based; the first page of the deck is its cover, not a card.
MARKER = "- evento de asentamiento -"

GENERATED_HEADER = "// Generated by tools/content-ingest/ingest_settlement_events.py. Do not edit by hand."

_NAME_INDENT = 24


@dataclass(frozen=True)
class Entry:
    name: str
    description: str


def _pages(pdf_path: Path) -> List[List[str]]:
    """Return the deck's pages as non-blank, stripped lines, with counts cross-checked."""
    text = pdf_text(pdf_path)
    raw_pages = [page for page in text.split(FORM_FEED) if page.strip()]

    declared_pages = pdf_info(pdf_path).get("Pages")
    if declared_pages is not None and int(declared_pages) != len(raw_pages):
        raise SystemExit(
            f"page split mismatch for {pdf_path.name}: pdfinfo says {declared_pages}, "
            f"split found {len(raw_pages)}"
        )

    return [[line.strip() for line in page.splitlines() if line.strip()] for page in raw_pages]


def parse_events(pdf_path: Path) -> List[Entry]:
    pages = _pages(pdf_path)

    entries: List[Entry] = []
    for page_number, lines in enumerate(pages, start=1):
        if page_number == TITLE_PAGE:
            if len(lines) >= 2 and lines[1] == MARKER:
                raise SystemExit(
                    f"{pdf_path.name} page 1 looks like a card, not the deck cover "
                    f"(first lines: {lines[:2]!r}); refusing to skip a card"
                )
            continue

        if len(lines) < 3 or lines[1] != MARKER:
            raise SystemExit(
                f"{pdf_path.name} page {page_number} is not a settlement-event card "
                f"(first lines: {lines[:2]!r}); refusing to silently drop it"
            )

        name = normalize_ws(lines[0])
        description = normalize_ws(" ".join(lines[2:]))
        if not name or not description:
            raise SystemExit(
                f"{pdf_path.name} page {page_number} has an empty name or text "
                f"(name: {name!r}); refusing to emit a blank event"
            )
        entries.append(Entry(name=name, description=description))

    if len(entries) != len(pages) - 1:
        raise SystemExit(
            f"{pdf_path.name}: parsed {len(entries)} cards from {len(pages)} pages but "
            "expected one cover page plus one card per page"
        )
    return entries


def dedupe_sorted(entries: Sequence[Entry], label: str) -> List[Entry]:
    by_name: Dict[str, Entry] = {}
    for entry in entries:
        if not entry.name or not entry.description:
            raise SystemExit(f"{label}: card {entry.name!r} has an empty name or text")
        existing = by_name.get(entry.name)
        if existing is not None and existing.description != entry.description:
            raise SystemExit(
                f"{label}: {entry.name!r} appears twice with different text; refusing to guess"
            )
        by_name[entry.name] = entry
    return sorted(by_name.values(), key=lambda entry: entry.name)


def _text_lines(text: str) -> List[str]:
    """Render the wrapped string as `text = …` instead of `description = …`."""
    return [line.replace("description =", "text =", 1) for line in description_lines(text)]


def _entry_lines(entry: Entry) -> List[str]:
    lines = [
        " " * 20 + "SettlementEvent(",
        f'{indent(_NAME_INDENT)}name = "{kotlin_escape(entry.name)}",',
    ]
    lines.extend(_text_lines(entry.description))
    lines.append(" " * 20 + "),")
    return lines


def emit_kotlin(events: Sequence[Entry]) -> str:
    lines = [
        GENERATED_HEADER,
        "package io.kdmtracker.core.content.generated",
        "",
        "import io.kdmtracker.core.content.ContentBundle",
        "import io.kdmtracker.core.domain.SettlementEvent",
        "",
        "object Core15SettlementEvents {",
        "    val bundle: ContentBundle =",
        "        ContentBundle(",
        "            settlementEvents =",
        "                listOf(",
    ]
    for entry in events:
        lines.extend(_entry_lines(entry))
    lines.extend(
        [
            "                ),",
            "        )",
            "}",
        ]
    )
    return "\n".join(lines) + "\n"


DEFAULT_PDF_RELATIVE = Path("external-assets/Juego Completo/Formato XL 86x146 mm/AF Eventos.pdf")
DEFAULT_OUT_RELATIVE = Path(
    "core/src/commonMain/kotlin/io/kdmtracker/core/content/generated/Core15SettlementEvents.kt"
)


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def main(argv: Optional[Sequence[str]] = None) -> int:
    repo_root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--pdf",
        type=Path,
        default=repo_root / DEFAULT_PDF_RELATIVE,
        help="path to AF Eventos.pdf",
    )
    parser.add_argument("--out", type=Path, default=repo_root / DEFAULT_OUT_RELATIVE, help="output Kotlin file")
    args = parser.parse_args(argv)

    if not args.pdf.is_file():
        parser.error(f"settlement events PDF not found: {args.pdf}\nPass --pdf <path> (external-assets/ is untracked).")

    events = dedupe_sorted(parse_events(args.pdf), "settlement events")
    output = emit_kotlin(events)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(output, encoding="utf-8")

    print(f"parsed {len(events)} settlement events -> {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
