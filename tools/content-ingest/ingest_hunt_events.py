#!/usr/bin/env python3
"""Parse the 1.5 hunt-event decks and emit committed Kotlin.

Reads the untracked ``AF Caza`` decks (see ``external-assets/``):

* ``AF Caza Básicos.pdf`` — basic and special hunt events.
* ``AF Caza León / Antílope / Fénix.pdf`` — each monster's hunt events.

Every deck renders one card per PDF page, so card boundaries need no guessing: page 1 is the
cover and every later page is a card whose second line is a type sub-line
(``- evento de caza básico -`` / ``- evento de caza especial -`` / ``- evento de caza de <monster> -``).
That sub-line is validated against the deck, so a shifted page aborts the run. The basic deck's
twelve identical ``Evento Aleatorio`` cards dedupe to one.

Determinism: no timestamps, no paths, entries deduped and sorted by name.
"""

from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))

from kotlin_emit import description_lines, indent, kotlin_escape, normalize_ws  # noqa: E402
from pdf_text import pdf_info, pdf_text  # noqa: E402

FORM_FEED = "\f"
TITLE_PAGE = 1  # 1-based; the first page of a deck is its cover, not a card.
BASIC_SUBLINE = "- evento de caza básico -"
SPECIAL_SUBLINE = "- evento de caza especial -"

GENERATED_HEADER = "// Generated by tools/content-ingest/ingest_hunt_events.py. Do not edit by hand."

_NAME_INDENT = 24


@dataclass(frozen=True)
class Entry:
    name: str
    description: str
    kind: str
    monster: Optional[str]


def _pages(pdf_path: Path) -> List[List[str]]:
    """Return the deck's pages as non-blank, stripped lines, with counts cross-checked."""
    text = pdf_text(pdf_path)
    raw_pages = [page for page in text.split(FORM_FEED) if page.strip()]

    declared_pages = pdf_info(pdf_path).get("Pages")
    if declared_pages is not None and int(declared_pages) != len(raw_pages):
        raise SystemExit(
            f"page split mismatch for {pdf_path.name}: pdfinfo says {declared_pages}, "
            f"split found {len(raw_pages)}"
        )

    return [[line.strip() for line in page.splitlines() if line.strip()] for page in raw_pages]


def _kind_for(subline: str, expected_subline: Optional[str], monster: Optional[str]) -> str:
    if monster is not None:
        if subline != expected_subline:
            raise SystemExit(f"expected {expected_subline!r}, found {subline!r}")
        return "MONSTER"
    if subline == BASIC_SUBLINE:
        return "BASIC"
    if subline == SPECIAL_SUBLINE:
        return "SPECIAL"
    raise SystemExit(f"unknown basic-deck sub-line {subline!r}")


def parse_deck(
    pdf_path: Path,
    *,
    monster: Optional[str],
    expected_subline: Optional[str],
) -> List[Entry]:
    pages = _pages(pdf_path)

    entries: List[Entry] = []
    for page_number, lines in enumerate(pages, start=1):
        if page_number == TITLE_PAGE:
            if len(lines) >= 2 and (lines[1] in (BASIC_SUBLINE, SPECIAL_SUBLINE) or "- evento de caza de" in lines[1]):
                raise SystemExit(
                    f"{pdf_path.name} page 1 looks like a card, not the cover "
                    f"(first lines: {lines[:2]!r}); refusing to skip a card"
                )
            continue

        if len(lines) < 3:
            raise SystemExit(f"{pdf_path.name} page {page_number} has too few lines: {lines!r}")
        kind = _kind_for(lines[1], expected_subline, monster)
        name = normalize_ws(lines[0])
        description = normalize_ws(" ".join(lines[2:]))
        if not name or not description:
            raise SystemExit(f"{pdf_path.name} page {page_number} has an empty name or text")
        entries.append(Entry(name=name, description=description, kind=kind, monster=monster))

    if len(entries) != len(pages) - 1:
        raise SystemExit(
            f"{pdf_path.name}: parsed {len(entries)} cards from {len(pages)} pages but "
            "expected one cover page plus one card per page"
        )
    return entries


def dedupe_sorted(entries: Sequence[Entry], label: str) -> List[Entry]:
    by_name: Dict[str, Entry] = {}
    for entry in entries:
        if not entry.name or not entry.description:
            raise SystemExit(f"{label}: card {entry.name!r} has an empty name or text")
        existing = by_name.get(entry.name)
        if existing is not None and existing.description != entry.description:
            raise SystemExit(
                f"{label}: {entry.name!r} appears twice with different text; refusing to guess"
            )
        by_name[entry.name] = entry
    return sorted(by_name.values(), key=lambda entry: entry.name)


def _text_lines(text: str) -> List[str]:
    return [line.replace("description =", "text =", 1) for line in description_lines(text)]


def _entry_lines(entry: Entry) -> List[str]:
    lines = [
        " " * 20 + "HuntEvent(",
        f'{indent(_NAME_INDENT)}name = "{kotlin_escape(entry.name)}",',
    ]
    lines.extend(_text_lines(entry.description))
    lines.append(f'{indent(_NAME_INDENT)}kind = HuntEventKind.{entry.kind},')
    if entry.monster is not None:
        lines.append(f'{indent(_NAME_INDENT)}monster = "{kotlin_escape(entry.monster)}",')
    lines.append(" " * 20 + "),")
    return lines


def emit_kotlin(events: Sequence[Entry]) -> str:
    lines = [
        GENERATED_HEADER,
        "package io.kdmtracker.core.content.generated",
        "",
        "import io.kdmtracker.core.content.ContentBundle",
        "import io.kdmtracker.core.domain.HuntEvent",
        "import io.kdmtracker.core.domain.HuntEventKind",
        "",
        "object Core15HuntEvents {",
        "    val bundle: ContentBundle =",
        "        ContentBundle(",
        "            huntEvents =",
        "                listOf(",
    ]
    for event in events:
        lines.extend(_entry_lines(event))
    lines.extend(
        [
            "                ),",
            "        )",
            "}",
        ]
    )
    return "\n".join(lines) + "\n"


BASIC_RELATIVE = Path("external-assets/Juego Completo/Formato Americano 57x88 mm/AF Caza/AF Caza Básicos.pdf")
# deck filename -> (catalog quarry name, the deck's monster sub-line)
MONSTER_DECKS: List[Tuple[str, str, str]] = [
    ("AF Caza León.pdf", "White Lion", "- evento de caza de león blanco -"),
    ("AF Caza Antílope.pdf", "Screaming Antelope", "- evento de caza de antílope bramador -"),
    ("AF Caza Fénix.pdf", "Phoenix", "- evento de caza de fénix -"),
]
DEFAULT_OUT_RELATIVE = Path(
    "core/src/commonMain/kotlin/io/kdmtracker/core/content/generated/Core15HuntEvents.kt"
)


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def main(argv: Optional[Sequence[str]] = None) -> int:
    repo_root = _repo_root()
    deck_dir = repo_root / BASIC_RELATIVE.parent
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dir", type=Path, default=deck_dir, help="directory holding the AF Caza decks")
    parser.add_argument("--out", type=Path, default=repo_root / DEFAULT_OUT_RELATIVE, help="output Kotlin file")
    args = parser.parse_args(argv)

    basic_path = args.dir / "AF Caza Básicos.pdf"
    if not basic_path.is_file():
        parser.error(f"hunt deck not found: {basic_path}\nPass --dir <dir> (external-assets/ is untracked).")

    entries: List[Entry] = parse_deck(basic_path, monster=None, expected_subline=None)
    for filename, monster, subline in MONSTER_DECKS:
        entries += parse_deck(args.dir / filename, monster=monster, expected_subline=subline)

    events = dedupe_sorted(entries, "hunt events")
    output = emit_kotlin(events)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(output, encoding="utf-8")

    print(f"parsed {len(events)} hunt events -> {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
