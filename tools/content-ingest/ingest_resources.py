#!/usr/bin/env python3
"""Parse the 1.5 resource cards and emit committed Kotlin.

Reads every deck under ``AF Recursos/`` (see ``external-assets/``), extracts one
resource per PDF page, and writes a deterministic ``Core15Resources.kt``.

Category model
--------------
A resource's :class:`ResourceCategory` is a property of the **deck** it ships in,
never of its material tags. ``hueso``/``órgano``/``piel``/``restos`` appear both on
basic cards ("Hueso de Monstruo") and on quarry cards ("Garra de León"), so the
tag alone cannot distinguish BASIC from MONSTER. The deck is the section, and the
section decides the category:

* ``AF Rec Básicos.pdf``      (``-Recursos Básicos-``)  -> ``BASIC``
* ``AF Rec Extraños.pdf``     (``-Recursos Extraños-``) -> ``SPECIAL``
* ``AF Rec Alimaña.pdf``      (``-Alimañas-``)          -> ``SPECIAL``
* ``AF RecPre <quarry>.pdf``  (Antílope / Fénix / León) -> ``MONSTER``

``Alimañas`` (vermin) are neither basic materials nor quarry/nemesis monster
cards; the enum has no ``VERMIN`` member, and vermin are the deck's "strange"
consumables, so ``SPECIAL`` is the closest existing category. This mapping is
explicit and every deck must be listed; an unrecognized deck aborts the run
rather than guessing a category.

Design notes
------------
* The PDF renders exactly one card per page, so card boundaries need no guessing:
  page 1 is the deck title, every later page is a card. ``pdfinfo`` page count is
  checked against the form-feed split and any page that does not parse as a card
  aborts the run (the integrity guard carried over from Ruling BN).
* The card's second line is its type line (a comma-separated list of material
  tags); it is validated against the known vocabulary so a shifted page is caught
  instead of silently mis-read.
* Determinism: no timestamps, no paths, entries deduped and sorted by name, and a
  name that appears in two decks with different categories aborts the run.
"""

from __future__ import annotations

import argparse
import sys
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))

from pdf_text import pdf_info, pdf_text  # noqa: E402

FORM_FEED = "\f"
TITLE_PAGE = 1  # 1-based; the first page is the deck's title, not a card.

# Deck file name -> ResourceCategory. The deck is the resource's section.
DECK_CATEGORIES: Dict[str, str] = {
    "AF Rec Básicos.pdf": "BASIC",
    "AF Rec Extraños.pdf": "SPECIAL",
    "AF Rec Alimaña.pdf": "SPECIAL",
    "AF RecPre Antílope.pdf": "MONSTER",
    "AF RecPre Fénix.pdf": "MONSTER",
    "AF RecPre León.pdf": "MONSTER",
}

# The material tags that may appear on a card's type line.
KNOWN_TAGS = {
    "hueso",
    "órgano",
    "piel",
    "restos",
    "consumible",
    "otro",
    "alimaña",
    "hierba",
    "hierro",
    "calavera",
}

GENERATED_HEADER = "// Generated by tools/content-ingest/ingest_resources.py. Do not edit by hand."

_NAME_INDENT = 24
_CARD_INDENT = 20
_LIST_INDENT = 16


@dataclass(frozen=True)
class Card:
    name: str
    tags: Tuple[str, ...]


def normalize_ws(text: str) -> str:
    return " ".join(text.split())


def nfc(text: str) -> str:
    """macOS stores filenames in NFD; compare against NFC literals."""
    return unicodedata.normalize("NFC", text)


def kotlin_escape(text: str) -> str:
    out = []
    for char in text:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "$":
            out.append("\\$")
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        else:
            out.append(char)
    return "".join(out)


def deck_title_page(lines: Sequence[str]) -> bool:
    """A title page is ``R`` followed by the deck name, never a type line."""
    return not looks_like_tags(lines[1]) if len(lines) >= 2 else True


def looks_like_tags(line: str) -> bool:
    tokens = [token.strip() for token in line.split(",") if token.strip()]
    return bool(tokens) and all(token in KNOWN_TAGS for token in tokens)


def parse_deck(pdf_path: Path, category: str) -> List[Tuple[str, str]]:
    text = pdf_text(pdf_path)
    pages = [page for page in text.split(FORM_FEED) if page.strip()]

    declared_pages = pdf_info(pdf_path).get("Pages")
    if declared_pages is not None and int(declared_pages) != len(pages):
        raise SystemExit(
            f"page split mismatch for {pdf_path.name}: pdfinfo says {declared_pages}, "
            f"split found {len(pages)}"
        )

    cards: List[Tuple[str, str]] = []
    for page_number, page in enumerate(pages, start=1):
        lines = [line.strip() for line in page.splitlines() if line.strip()]

        if page_number == TITLE_PAGE:
            if not deck_title_page(lines):
                raise SystemExit(
                    f"{pdf_path.name} page 1 looks like a card, not the deck title "
                    f"(first lines: {lines[:2]!r}); refusing to skip a card"
                )
            continue

        if len(lines) < 2:
            raise SystemExit(
                f"{pdf_path.name} page {page_number} is too short to be a resource card "
                f"(first lines: {lines!r}); refusing to silently drop it"
            )

        name, type_line = lines[0], lines[1]
        if not looks_like_tags(type_line):
            raise SystemExit(
                f"{pdf_path.name} page {page_number} ({name!r}) has an unrecognized type line "
                f"{type_line!r}; refusing to guess a category"
            )

        tags = tuple(token.strip() for token in type_line.split(",") if token.strip())
        cards.append((normalize_ws(name), category))

    return cards


def collect_resources(pdf_dir: Path) -> List[Tuple[str, str]]:
    pdfs = sorted(pdf_dir.glob("*.pdf"), key=lambda pdf: nfc(pdf.name))
    names = {nfc(pdf.name) for pdf in pdfs}
    missing = sorted(set(DECK_CATEGORIES) - names)
    unknown = sorted(names - set(DECK_CATEGORIES))
    if missing or unknown:
        raise SystemExit(
            f"deck set mismatch in {pdf_dir}: missing {missing}, unknown {unknown}; "
            "every resource deck must have an explicit category mapping"
        )

    category_by_name: Dict[str, str] = {}
    for pdf in pdfs:
        category = DECK_CATEGORIES[nfc(pdf.name)]
        for name, card_category in parse_deck(pdf, category):
            existing = category_by_name.get(name)
            if existing is not None and existing != card_category:
                raise SystemExit(
                    f"resource {name!r} appears as both {existing} and {card_category}; "
                    "refusing to guess"
                )
            category_by_name[name] = card_category

    return sorted(category_by_name.items(), key=lambda item: item[0])


def emit_kotlin(resources: Sequence[Tuple[str, str]]) -> str:
    lines = [
        GENERATED_HEADER,
        "package io.kdmtracker.core.content.generated",
        "",
        "import io.kdmtracker.core.content.ContentBundle",
        "import io.kdmtracker.core.domain.ResourceCategory",
        "import io.kdmtracker.core.domain.ResourceDefinition",
        "",
        "object Core15Resources {",
        "    val bundle: ContentBundle =",
        "        ContentBundle(",
        "            resources =",
        "                listOf(",
    ]
    for name, category in resources:
        lines.append(" " * _CARD_INDENT + "ResourceDefinition(")
        lines.append(f'{_indent(_NAME_INDENT)}name = "{kotlin_escape(name)}",')
        lines.append(f"{_indent(_NAME_INDENT)}category = ResourceCategory.{category},")
        lines.append(" " * _CARD_INDENT + "),")
    lines.extend(
        [
            " " * _LIST_INDENT + "),",
            "        )",
            "}",
        ]
    )
    return "\n".join(lines) + "\n"


def _indent(width: int) -> str:
    return " " * width


DEFAULT_PDF_DIR_RELATIVE = Path("external-assets/Juego Completo/Formato Americano 57x88 mm/AF Recursos")
DEFAULT_OUT_RELATIVE = Path("core/src/commonMain/kotlin/io/kdmtracker/core/content/generated/Core15Resources.kt")


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def main(argv: Optional[Sequence[str]] = None) -> int:
    repo_root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--pdf-dir",
        type=Path,
        default=repo_root / DEFAULT_PDF_DIR_RELATIVE,
        help="directory holding the AF Recursos*.pdf decks",
    )
    parser.add_argument("--out", type=Path, default=repo_root / DEFAULT_OUT_RELATIVE, help="output Kotlin file")
    args = parser.parse_args(argv)

    if not args.pdf_dir.is_dir():
        parser.error(f"PDF directory not found: {args.pdf_dir}\nPass --pdf-dir <path> (external-assets/ is untracked).")

    resources = collect_resources(args.pdf_dir)
    output = emit_kotlin(resources)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(output, encoding="utf-8")

    by_category: Dict[str, int] = {}
    for _, category in resources:
        by_category[category] = by_category.get(category, 0) + 1
    print(
        f"parsed {len(resources)} unique resources ({by_category}) -> {args.out}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
