#!/usr/bin/env python3
"""Parse the 1.5 resource cards and emit committed Kotlin.

Reads every deck under ``AF Recursos/`` (see ``external-assets/``), extracts one
resource per PDF page, and writes a deterministic ``Core15Resources.kt``.

Category model
--------------
A resource's :class:`ResourceCategory` is a property of the **deck** it ships in,
never of its material tags. ``hueso``/``órgano``/``piel``/``restos`` appear both on
basic cards ("Hueso de Monstruo") and on quarry cards ("Garra de León"), so the
tag alone cannot distinguish BASIC from MONSTER. The deck is the section, and the
section decides the category:

* ``AF Rec Básicos.pdf``      (``-Recursos Básicos-``)  -> ``BASIC``
* ``AF Rec Extraños.pdf``     (``-Recursos Extraños-``) -> ``SPECIAL``
* ``AF Rec Alimaña.pdf``      (``-Alimañas-``)          -> ``SPECIAL``
* ``AF RecPre <quarry>.pdf``  (Antílope / Fénix / León) -> ``MONSTER``

``Alimañas`` (vermin) are neither basic materials nor quarry/nemesis monster
cards; the enum has no ``VERMIN`` member, and vermin are the deck's "strange"
consumables, so ``SPECIAL`` is the closest existing category. This mapping is
explicit and every deck must be listed; an unrecognized deck aborts the run
rather than guessing a category.

Design notes
------------
* The PDF renders exactly one card per page, so card boundaries need no guessing:
  page 1 is the deck title, every later page is a card. ``pdfinfo`` page count is
  checked against the form-feed split and any page that does not parse as a card
  aborts the run (the integrity guard carried over from Ruling BN).
* The card's second line is its type line (a comma-separated list of material
  tags); it is validated against the known vocabulary so a shifted page is caught
  instead of silently mis-read.
* Determinism: no timestamps, no paths, entries deduped and sorted by name, and a
  name that appears in two decks with different categories aborts the run.
"""

from __future__ import annotations

import argparse
import csv
import sys
import unicodedata
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, FrozenSet, List, Optional, Sequence, Tuple

sys.path.insert(0, str(Path(__file__).resolve().parent))

from kotlin_emit import indent, kotlin_escape, normalize_ws  # noqa: E402
from pdf_text import pdf_info, pdf_text  # noqa: E402

FORM_FEED = "\f"
TITLE_PAGE = 1  # 1-based; the first page is the deck's title, not a card.

# Deck file name -> ResourceCategory. The deck is the resource's section.
DECK_CATEGORIES: Dict[str, str] = {
    "AF Rec Básicos.pdf": "BASIC",
    "AF Rec Extraños.pdf": "SPECIAL",
    "AF Rec Alimaña.pdf": "SPECIAL",
    "AF RecPre Antílope.pdf": "MONSTER",
    "AF RecPre Fénix.pdf": "MONSTER",
    "AF RecPre León.pdf": "MONSTER",
}

# A card in the Básicos deck is genuinely named "???" (an unidentified monster part).
UNKNOWN_RESOURCE_NAME = "???"

# The material tags that may appear on a card's type line.
KNOWN_TAGS = {
    "hueso",
    "órgano",
    "piel",
    "restos",
    "consumible",
    "otro",
    "alimaña",
    "hierba",
    "hierro",
    "calavera",
}

# The four tags that name a settlement-summary bucket. The rest (hierba, hierro, calavera,
# consumible, otro, alimaña) decide nothing: a card carrying none of these four feeds no bucket and
# its material is null, which is a legitimate answer rather than a gap to fill.
PRIMARY_MATERIAL_BY_TAG = {
    "hueso": "BONE",
    "órgano": "ORGAN",
    "piel": "HIDE",
    "restos": "SCRAP",
}

MATERIALS = frozenset(PRIMARY_MATERIAL_BY_TAG.values())

IDENTITY_HEADER = ("id", "spanishName", "englishName")

GENERATED_HEADER = "// Generated by tools/content-ingest/ingest_resources.py. Do not edit by hand."

_NAME_INDENT = 24
_CARD_INDENT = 20
_LIST_INDENT = 16


@dataclass(frozen=True)
class Resource:
    name: str
    category: str
    tags: Tuple[str, ...]


@dataclass(frozen=True)
class IdentityRow:
    """One row of ``identity/resources.csv``: a card's stable id and its optional English name."""

    resource_id: str
    english_name: str


def load_identity(csv_path: Path) -> Dict[str, IdentityRow]:
    """Read the identity CSV, keyed by the Spanish card name it must match exactly."""
    if not csv_path.is_file():
        raise SystemExit(f"identity CSV not found: {csv_path}")

    rows: Dict[str, IdentityRow] = {}
    with csv_path.open(encoding="utf-8", newline="") as handle:
        reader = csv.DictReader(handle)
        header = tuple(reader.fieldnames or ())
        if header != IDENTITY_HEADER:
            raise SystemExit(f"identity CSV header must be {IDENTITY_HEADER}, got {header}")
        for raw in reader:
            spanish = normalize_ws(raw["spanishName"])
            if spanish in rows:
                raise SystemExit(f"identity CSV repeats the name {spanish!r}")
            rows[spanish] = IdentityRow(
                resource_id=normalize_ws(raw["id"]),
                english_name=normalize_ws(raw["englishName"]),
            )
    return rows


def materials_for(tags: Sequence[str]) -> FrozenSet[str]:
    """
    The summary buckets a card can pay — **every** primary tag it carries.

    A card's type line lists the materials it counts as, and it can be spent as any of them, so the
    set is its type line read through [PRIMARY_MATERIAL_BY_TAG] and nothing else:

    * one tag  -> an ordinary resource, which the summary counts in that bucket;
    * no tag   -> an empty set: a herb, a bar of iron or a skull feeds none of the four cells;
    * several  -> a wildcard. The `???` card is tagged `hueso, órgano, piel` because it pays a bone,
      a hide *or* an organ. Held in storage it is committed to none of them, and the summary counts
      only a one-element set, so counting it in each bucket would inflate the stock.
    """
    return frozenset(PRIMARY_MATERIAL_BY_TAG[tag] for tag in tags if tag in PRIMARY_MATERIAL_BY_TAG)


def nfc(text: str) -> str:
    """macOS stores filenames in NFD; compare against NFC literals."""
    return unicodedata.normalize("NFC", text)


def deck_title_page(lines: Sequence[str]) -> bool:
    """A title page is ``R`` followed by the deck name, never a type line."""
    return not looks_like_tags(lines[1]) if len(lines) >= 2 else True


def looks_like_tags(line: str) -> bool:
    tokens = [token.strip() for token in line.split(",") if token.strip()]
    return bool(tokens) and all(token in KNOWN_TAGS for token in tokens)


def parse_deck(pdf_path: Path, category: str) -> List[Resource]:
    text = pdf_text(pdf_path)
    pages = [page for page in text.split(FORM_FEED) if page.strip()]

    declared_pages = pdf_info(pdf_path).get("Pages")
    if declared_pages is not None and int(declared_pages) != len(pages):
        raise SystemExit(
            f"page split mismatch for {pdf_path.name}: pdfinfo says {declared_pages}, "
            f"split found {len(pages)}"
        )

    cards: List[Resource] = []
    for page_number, page in enumerate(pages, start=1):
        lines = [line.strip() for line in page.splitlines() if line.strip()]

        if page_number == TITLE_PAGE:
            if not deck_title_page(lines):
                raise SystemExit(
                    f"{pdf_path.name} page 1 looks like a card, not the deck title "
                    f"(first lines: {lines[:2]!r}); refusing to skip a card"
                )
            continue

        if len(lines) < 2:
            raise SystemExit(
                f"{pdf_path.name} page {page_number} is too short to be a resource card "
                f"(first lines: {lines!r}); refusing to silently drop it"
            )

        name, type_line = lines[0], lines[1]
        if not looks_like_tags(type_line):
            raise SystemExit(
                f"{pdf_path.name} page {page_number} ({name!r}) has an unrecognized type line "
                f"{type_line!r}; refusing to guess a category"
            )

        tags = tuple(token.strip() for token in type_line.split(",") if token.strip())
        cards.append(Resource(name=normalize_ws(name), category=category, tags=tags))

    return cards


def collect_resources(pdf_dir: Path) -> List[Resource]:
    pdfs = sorted(pdf_dir.glob("*.pdf"), key=lambda pdf: nfc(pdf.name))
    names = {nfc(pdf.name) for pdf in pdfs}
    missing = sorted(set(DECK_CATEGORIES) - names)
    unknown = sorted(names - set(DECK_CATEGORIES))
    if missing or unknown:
        raise SystemExit(
            f"deck set mismatch in {pdf_dir}: missing {missing}, unknown {unknown}; "
            "every resource deck must have an explicit category mapping"
        )

    by_name: Dict[str, Resource] = {}
    for pdf in pdfs:
        category = DECK_CATEGORIES[nfc(pdf.name)]
        for card in parse_deck(pdf, category):
            existing = by_name.get(card.name)
            if existing is not None and existing.category != card.category:
                raise SystemExit(
                    f"resource {card.name!r} appears as both {existing.category} and "
                    f"{card.category}; refusing to guess"
                )
            by_name[card.name] = card

    return sorted(by_name.values(), key=lambda resource: resource.name)


def emit_kotlin(resources: Sequence[Resource], identity: Dict[str, IdentityRow]) -> str:
    lines = [
        GENERATED_HEADER,
        "package io.kdmtracker.core.content.generated",
        "",
        "import io.kdmtracker.core.content.ContentBundle",
        "import io.kdmtracker.core.domain.LocalizedText",
        "import io.kdmtracker.core.domain.ResourceCategory",
        "import io.kdmtracker.core.domain.ResourceDefinition",
        "import io.kdmtracker.core.domain.ResourceId",
        "import io.kdmtracker.core.domain.ResourceMaterial",
        "",
        "object Core15Resources {",
        "    val bundle: ContentBundle =",
        "        ContentBundle(",
        "            resources =",
        "                listOf(",
    ]
    for resource in resources:
        row = identity[resource.name]
        materials = materials_for(resource.tags)
        names = f'LocalizedText(es = "{kotlin_escape(resource.name)}"'
        if row.english_name:
            names += f', en = "{kotlin_escape(row.english_name)}"'
        names += ")"
        lines.append(" " * _CARD_INDENT + "ResourceDefinition(")
        if resource.name == UNKNOWN_RESOURCE_NAME:
            # The Básicos deck prints a card literally named "???" (an unidentified monster
            # part): this is the real card name, not a parse artifact. It appears twice with
            # identical text and is deduped to one BASIC entry. It is a wildcard: it pays a
            # bone, a hide or an organ, so it carries all three materials.
            lines.append(f"{indent(_NAME_INDENT)}// Literal card name from AF Rec Básicos.pdf — not a parse placeholder.")
        lines.append(f'{indent(_NAME_INDENT)}id = ResourceId("{kotlin_escape(row.resource_id)}"),')
        lines.append(f"{indent(_NAME_INDENT)}names = {names},")
        lines.append(f"{indent(_NAME_INDENT)}category = ResourceCategory.{resource.category},")
        if materials:
            rendered = ", ".join(f"ResourceMaterial.{material}" for material in sorted(materials))
            lines.append(f"{indent(_NAME_INDENT)}materials = setOf({rendered}),")
        else:
            # None of the card's tags names a summary bucket (a herb, a bar of iron, a skull).
            # That is the answer, not a gap: the resource is real and simply not in the grid.
            lines.append(f"{indent(_NAME_INDENT)}materials = emptySet(),")
        lines.append(" " * _CARD_INDENT + "),")
    lines.extend(
        [
            " " * _LIST_INDENT + "),",
            "        )",
            "}",
        ]
    )
    return "\n".join(lines) + "\n"


DEFAULT_PDF_DIR_RELATIVE = Path("external-assets/Juego Completo/Formato Americano 57x88 mm/AF Recursos")
DEFAULT_OUT_RELATIVE = Path("core/src/commonMain/kotlin/io/kdmtracker/core/content/generated/Core15Resources.kt")
DEFAULT_IDENTITY_RELATIVE = Path("tools/content-ingest/identity/resources.csv")


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def main(argv: Optional[Sequence[str]] = None) -> int:
    repo_root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--pdf-dir",
        type=Path,
        default=repo_root / DEFAULT_PDF_DIR_RELATIVE,
        help="directory holding the AF Recursos*.pdf decks",
    )
    parser.add_argument("--out", type=Path, default=repo_root / DEFAULT_OUT_RELATIVE, help="output Kotlin file")
    parser.add_argument(
        "--identity",
        type=Path,
        default=repo_root / DEFAULT_IDENTITY_RELATIVE,
        help="CSV giving each card's stable id, optional English name and optional material override",
    )
    args = parser.parse_args(argv)

    if not args.pdf_dir.is_dir():
        parser.error(f"PDF directory not found: {args.pdf_dir}\nPass --pdf-dir <path> (external-assets/ is untracked).")

    resources = collect_resources(args.pdf_dir)
    identity = load_identity(args.identity)

    parsed_names = {resource.name for resource in resources}
    unmapped = sorted(parsed_names - set(identity))
    if unmapped:
        raise SystemExit(
            f"{len(unmapped)} card(s) in {args.pdf_dir.name} have no row in {args.identity}: {unmapped}; "
            "every card needs a stable id before it can be emitted"
        )
    # Rows that match no card here are not an error: the CSV is the identity table for every pack,
    # and the hand-written 1.6 seed names resources the 1.5 decks do not carry (its "Scrap"). A
    # mistyped Spanish name cannot slip through this way — the card it meant to cover would be
    # unmapped, and the check above has already aborted on that.
    unmatched = sorted(set(identity) - parsed_names)
    if unmatched:
        print(
            f"note: {len(unmatched)} identity row(s) cover no card in this deck set "
            f"(other packs' names): {unmatched}",
            file=sys.stderr,
        )

    output = emit_kotlin(resources, identity)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(output, encoding="utf-8")

    by_category: Dict[str, int] = {}
    by_material: Dict[str, int] = {}
    for resource in resources:
        by_category[resource.category] = by_category.get(resource.category, 0) + 1
        materials = materials_for(resource.tags)
        if not materials:
            key = "none"
        elif len(materials) == 1:
            key = next(iter(materials))
        else:
            key = "wildcard"
        by_material[key] = by_material.get(key, 0) + 1
    print(
        f"parsed {len(resources)} unique resources ({by_category}) -> {args.out}\n"
        f"  materials: {by_material}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
