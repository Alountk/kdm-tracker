#!/usr/bin/env python3
"""Parse the 1.5 fighting-art and disorder cards and emit committed Kotlin.

Reads two untracked decks (see ``external-assets/``):

* ``AF Artes de Combate/AF Artes de Combate.pdf`` — the fighting arts.
* ``AF Trastornos.pdf`` — the disorders.

Both render exactly one card per PDF page, so card boundaries need no guessing:
page 1 is each deck's title and every later page is a card. The two decks carry a
different card shape, so each is parsed by its own recognizer:

* A **fighting-art** card's second line is its type line (``- arte de combate -``
  or ``- arte de combate, cepa -``). The type line is validated against that
  exact vocabulary, so a shifted page is caught instead of silently mis-read.
* A **disorder** card has no type line; its last line is the ``Anota y retira``
  reminder that closes every card. That footer is the card recognizer: a page
  that does not end with it aborts the run.

Everything that is not the name, the type line, or the footer is the effect text
(``description``). Cards are extracted into a minimal
:class:`~io.kdmtracker.core.domain.ContentEntry` (name + description).

Design notes
------------
* The integrity guard carried over from Ruling BN: ``pdfinfo``'s page count is
  checked against the form-feed split, the parsed card count is asserted against
  ``pages - 1`` (one title page), and any page that does not parse as a card
  aborts the run rather than being dropped.
* Determinism: no timestamps, no paths, entries deduped and sorted by name.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parent))

from pdf_text import pdf_info, pdf_text  # noqa: E402

FORM_FEED = "\f"
TITLE_PAGE = 1  # 1-based; the first page of a deck is its title, not a card.
FOOTER = "Anota y retira"

ART_TYPE_RE = re.compile(r"^- arte de combate(?:, cepa)? -$")

GENERATED_HEADER = "// Generated by tools/content-ingest/ingest_fighting_arts.py. Do not edit by hand."

_NAME_INDENT = 24
_DESC_KEY_INDENT = 24
_DESC_FIRST_INDENT = 28
_DESC_CONT_INDENT = 32
# An inlined `description = "…",` occupies 24 + len('description = "') + "…" + '",' = len + 41.
_DESC_INLINE_MAX = 120 - 41
_DESC_CHUNK_MAX = 80


@dataclass(frozen=True)
class Entry:
    name: str
    description: str


def normalize_ws(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def kotlin_escape(text: str) -> str:
    out = []
    for char in text:
        if char == "\\":
            out.append("\\\\")
        elif char == '"':
            out.append('\\"')
        elif char == "$":
            out.append("\\$")
        elif char == "\n":
            out.append("\\n")
        elif char == "\r":
            out.append("\\r")
        elif char == "\t":
            out.append("\\t")
        else:
            out.append(char)
    return "".join(out)


def _pages(pdf_path: Path) -> List[List[str]]:
    """Return the deck's pages as non-blank, stripped lines, with counts cross-checked."""
    text = pdf_text(pdf_path)
    raw_pages = [page for page in text.split(FORM_FEED) if page.strip()]

    declared_pages = pdf_info(pdf_path).get("Pages")
    if declared_pages is not None and int(declared_pages) != len(raw_pages):
        raise SystemExit(
            f"page split mismatch for {pdf_path.name}: pdfinfo says {declared_pages}, "
            f"split found {len(raw_pages)}"
        )

    return [[line.strip() for line in page.splitlines() if line.strip()] for page in raw_pages]


def parse_fighting_arts(pdf_path: Path) -> List[Entry]:
    pages = _pages(pdf_path)

    entries: List[Entry] = []
    for page_number, lines in enumerate(pages, start=1):
        if page_number == TITLE_PAGE:
            if len(lines) >= 2 and ART_TYPE_RE.match(lines[1]):
                raise SystemExit(
                    f"{pdf_path.name} page 1 looks like a card, not the deck title "
                    f"(first lines: {lines[:2]!r}); refusing to skip a card"
                )
            continue

        if len(lines) < 3 or not ART_TYPE_RE.match(lines[1]):
            raise SystemExit(
                f"{pdf_path.name} page {page_number} is not a fighting-art card "
                f"(first lines: {lines[:2]!r}); refusing to silently drop it"
            )

        if lines[-1] != FOOTER:
            raise SystemExit(
                f"{pdf_path.name} page {page_number} ({lines[0]!r}) does not end with "
                f"{FOOTER!r} (last line: {lines[-1]!r}); refusing to guess card boundaries"
            )

        description = normalize_ws(" ".join(lines[2:-1]))
        entries.append(Entry(name=normalize_ws(lines[0]), description=description))

    if len(entries) != len(pages) - 1:
        raise SystemExit(
            f"{pdf_path.name}: parsed {len(entries)} cards from {len(pages)} pages but "
            "expected one title page plus one card per page"
        )
    return entries


def parse_disorders(pdf_path: Path) -> List[Entry]:
    pages = _pages(pdf_path)

    entries: List[Entry] = []
    for page_number, lines in enumerate(pages, start=1):
        if page_number == TITLE_PAGE:
            if lines[-1] == FOOTER:
                raise SystemExit(
                    f"{pdf_path.name} page 1 looks like a card, not the deck title "
                    f"(first lines: {lines[:2]!r}); refusing to skip a card"
                )
            continue

        if len(lines) < 3 or lines[-1] != FOOTER:
            raise SystemExit(
                f"{pdf_path.name} page {page_number} is not a disorder card "
                f"(first line: {lines[0]!r}, last line: {lines[-1]!r}); refusing to silently drop it"
            )

        description = normalize_ws(" ".join(lines[1:-1]))
        entries.append(Entry(name=normalize_ws(lines[0]), description=description))

    if len(entries) != len(pages) - 1:
        raise SystemExit(
            f"{pdf_path.name}: parsed {len(entries)} cards from {len(pages)} pages but "
            "expected one title page plus one card per page"
        )
    return entries


def dedupe_sorted(entries: Sequence[Entry], label: str) -> List[Entry]:
    by_name: Dict[str, Entry] = {}
    for entry in entries:
        if not entry.name or not entry.description:
            raise SystemExit(f"{label}: card {entry.name!r} has an empty name or description")
        existing = by_name.get(entry.name)
        if existing is not None and existing.description != entry.description:
            raise SystemExit(
                f"{label}: {entry.name!r} appears twice with different descriptions; refusing to guess"
            )
        by_name[entry.name] = entry
    return sorted(by_name.values(), key=lambda entry: entry.name)


def _chunk_for_wrapping(escaped: str, budget: int) -> List[str]:
    words = escaped.split(" ")
    chunks: List[List[str]] = []
    current: List[str] = []
    current_len = 0
    for word in words:
        extra = len(word) + (1 if current else 0)
        if current and current_len + extra > budget:
            chunks.append(current)
            current = [word]
            current_len = len(word)
        else:
            current.append(word)
            current_len += extra
    if current:
        chunks.append(current)
    joined = [" ".join(chunk) for chunk in chunks]
    return [chunk + " " for chunk in joined[:-1]] + [joined[-1]]


def _description_lines(description: str) -> List[str]:
    escaped = kotlin_escape(description)
    if len(escaped) <= _DESC_INLINE_MAX:
        return [f'{_indent(_DESC_KEY_INDENT)}description = "{escaped}",']

    chunks = _chunk_for_wrapping(escaped, _DESC_CHUNK_MAX)
    lines = [f"{_indent(_DESC_KEY_INDENT)}description ="]
    for index, chunk in enumerate(chunks):
        indent = _DESC_FIRST_INDENT if index == 0 else _DESC_CONT_INDENT
        suffix = " +" if index < len(chunks) - 1 else ","
        lines.append(f'{_indent(indent)}"{chunk}"{suffix}')
    return lines


def _entry_lines(entry: Entry) -> List[str]:
    lines = [
        " " * 20 + "ContentEntry(",
        f'{_indent(_NAME_INDENT)}name = "{kotlin_escape(entry.name)}",',
    ]
    lines.extend(_description_lines(entry.description))
    lines.append(" " * 20 + "),")
    return lines


def emit_kotlin(fighting_arts: Sequence[Entry], disorders: Sequence[Entry]) -> str:
    lines = [
        GENERATED_HEADER,
        "package io.kdmtracker.core.content.generated",
        "",
        "import io.kdmtracker.core.content.ContentBundle",
        "import io.kdmtracker.core.domain.ContentEntry",
        "",
        "object Core15FightingArts {",
        "    val bundle: ContentBundle =",
        "        ContentBundle(",
        "            fightingArts =",
        "                listOf(",
    ]
    for entry in fighting_arts:
        lines.extend(_entry_lines(entry))
    lines.extend(
        [
            "                ),",
            "            disorders =",
            "                listOf(",
        ]
    )
    for entry in disorders:
        lines.extend(_entry_lines(entry))
    lines.extend(
        [
            "                ),",
            "        )",
            "}",
        ]
    )
    return "\n".join(lines) + "\n"


def _indent(width: int) -> str:
    return " " * width


DEFAULT_COMBATE_RELATIVE = Path(
    "external-assets/Juego Completo/Formato Americano 57x88 mm/AF Artes de Combate/AF Artes de Combate.pdf"
)
DEFAULT_TRASTORNOS_RELATIVE = Path(
    "external-assets/Juego Completo/Formato Americano 57x88 mm/AF Trastornos.pdf"
)
DEFAULT_OUT_RELATIVE = Path(
    "core/src/commonMain/kotlin/io/kdmtracker/core/content/generated/Core15FightingArts.kt"
)


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def main(argv: Optional[Sequence[str]] = None) -> int:
    repo_root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument(
        "--combate",
        type=Path,
        default=repo_root / DEFAULT_COMBATE_RELATIVE,
        help="path to AF Artes de Combate.pdf",
    )
    parser.add_argument(
        "--trastornos",
        type=Path,
        default=repo_root / DEFAULT_TRASTORNOS_RELATIVE,
        help="path to AF Trastornos.pdf",
    )
    parser.add_argument("--out", type=Path, default=repo_root / DEFAULT_OUT_RELATIVE, help="output Kotlin file")
    args = parser.parse_args(argv)

    for label, path in (("fighting arts", args.combate), ("disorders", args.trastornos)):
        if not path.is_file():
            parser.error(f"{label} PDF not found: {path}\nPass --combate/--trastornos <path> (external-assets/ is untracked).")

    fighting_arts = dedupe_sorted(parse_fighting_arts(args.combate), "fighting arts")
    disorders = dedupe_sorted(parse_disorders(args.trastornos), "disorders")
    output = emit_kotlin(fighting_arts, disorders)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(output, encoding="utf-8")

    print(
        f"parsed {len(fighting_arts)} fighting arts + {len(disorders)} disorders -> {args.out}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
