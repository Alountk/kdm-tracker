#!/usr/bin/env python3
"""Parse the 1.5 monster showdown decks and emit committed Kotlin.

Reads ``AF Enfrentamientos/<monster>/`` (see ``external-assets/``): each monster folder holds its
AI deck (``AF AI <monster>.pdf``) and its hit-location deck (``AF HL <monster>.pdf``). The
``AF AI <monster> - Acción Básica.pdf`` files duplicate the AI deck, so they are not ingested.

One card per PDF page: page 1 is the cover. An AI card's top lines are an optional ``xN`` quantity
and a rank letter (``B``/``A``/``L``/``S``), then the name; a hit-location card's first line is its
name. Determinism: no timestamps/paths, entries deduped and sorted.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Optional, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parent))

from kotlin_emit import description_lines, indent, kotlin_escape, normalize_ws  # noqa: E402
from pdf_text import pdf_info, pdf_text  # noqa: E402

FORM_FEED = "\f"
TITLE_PAGE = 1
RANKS = {"B", "A", "L", "S"}
QUANTITY_RE = re.compile(r"^x\d+$")

GENERATED_HEADER = "// Generated by tools/content-ingest/ingest_monsters.py. Do not edit by hand."
_NAME_INDENT = 24

# folder name -> the catalog monster name.
FOLDERS: Dict[str, str] = {
    "01 León Blanco": "White Lion",
    "02 Antílope Bramador": "Screaming Antelope",
    "03 Fénix": "Phoenix",
    "04 Carnicero": "The Butcher",
    "05 Hombre del Rey": "King's Man",
    "06 La Mano": "The Hand",
    "07 El Vigilante": "The Watcher",
    "08 Caballero Humo Dorado": "Golden Smoke Knight",
}


@dataclass(frozen=True)
class Entry:
    name: str
    description: str
    kind: str
    monster: str
    rank: Optional[str]


def _pages(pdf_path: Path) -> List[List[str]]:
    text = pdf_text(pdf_path)
    raw_pages = [page for page in text.split(FORM_FEED) if page.strip()]
    declared_pages = pdf_info(pdf_path).get("Pages")
    if declared_pages is not None and int(declared_pages) != len(raw_pages):
        raise SystemExit(
            f"page split mismatch for {pdf_path.name}: pdfinfo says {declared_pages}, "
            f"split found {len(raw_pages)}"
        )
    return [[line.strip() for line in page.splitlines() if line.strip()] for page in raw_pages]


def parse_ai_deck(pdf_path: Path, *, monster: str) -> List[Entry]:
    pages = _pages(pdf_path)
    entries: List[Entry] = []
    for page_number, lines in enumerate(pages, start=1):
        if page_number == TITLE_PAGE:
            continue
        # Some decks carry the monster's stat sheet (not a card) and the Basic Action card.
        if lines and lines[0] == "Acción Básica":
            description = normalize_ws(" ".join(lines[1:]))
            if not description:
                raise SystemExit(f"{pdf_path.name} page {page_number} has an empty basic action")
            entries.append(Entry("Acción Básica", description, "BASIC_ACTION", monster, None))
            continue
        if len(lines) >= 2 and lines[1].startswith("Nivel"):
            continue
        index = 1 if lines and QUANTITY_RE.match(lines[0]) else 0
        if len(lines) < index + 3 or lines[index] not in RANKS:
            raise SystemExit(
                f"{pdf_path.name} page {page_number} is not an AI card (first lines: {lines[:3]!r})"
            )
        rank = lines[index]
        name = normalize_ws(lines[index + 1])
        description = normalize_ws(" ".join(lines[index + 2 :]))
        if not name or not description:
            raise SystemExit(f"{pdf_path.name} page {page_number} has an empty name or text")
        entries.append(Entry(name=name, description=description, kind="AI", monster=monster, rank=rank))
    return entries


def parse_hit_locations(pdf_path: Path, *, monster: str) -> List[Entry]:
    pages = _pages(pdf_path)
    entries: List[Entry] = []
    for page_number, lines in enumerate(pages, start=1):
        if page_number == TITLE_PAGE:
            continue
        if len(lines) < 2:
            raise SystemExit(f"{pdf_path.name} page {page_number} does not look like a hit location")
        name = normalize_ws(lines[0])
        description = normalize_ws(" ".join(lines[1:]))
        if not name or not description:
            raise SystemExit(f"{pdf_path.name} page {page_number} has an empty name or text")
        entries.append(
            Entry(name=name, description=description, kind="HIT_LOCATION", monster=monster, rank=None)
        )
    return entries


def dedupe_sorted(entries: Sequence[Entry], label: str) -> List[Entry]:
    by_key: Dict[tuple, Entry] = {}
    for entry in entries:
        if not entry.name or not entry.description:
            raise SystemExit(f"{label}: card {entry.name!r} has an empty name or text")
        key = (entry.monster, entry.kind, entry.name)
        existing = by_key.get(key)
        if existing is not None and existing.description != entry.description:
            raise SystemExit(f"{label}: {key!r} appears twice with different text; refusing to guess")
        by_key[key] = entry
    return sorted(by_key.values(), key=lambda e: (e.monster, e.kind, e.name))


def _entry_lines(entry: Entry) -> List[str]:
    lines = [
        " " * 20 + "MonsterCard(",
        f'{indent(_NAME_INDENT)}name = "{kotlin_escape(entry.name)}",',
    ]
    lines.extend(
        [line.replace("description =", "text =", 1) for line in description_lines(entry.description)]
    )
    lines.append(f"{indent(_NAME_INDENT)}kind = MonsterCardKind.{entry.kind},")
    lines.append(f'{indent(_NAME_INDENT)}monster = "{kotlin_escape(entry.monster)}",')
    if entry.rank is not None:
        lines.append(f'{indent(_NAME_INDENT)}rank = "{kotlin_escape(entry.rank)}",')
    lines.append(" " * 20 + "),")
    return lines


def emit_kotlin(entries: Sequence[Entry]) -> str:
    lines = [
        GENERATED_HEADER,
        "package io.kdmtracker.core.content.generated",
        "",
        "import io.kdmtracker.core.content.ContentBundle",
        "import io.kdmtracker.core.domain.MonsterCard",
        "import io.kdmtracker.core.domain.MonsterCardKind",
        "",
        "object Core15Monsters {",
        "    val bundle: ContentBundle =",
        "        ContentBundle(",
        "            monsterCards =",
        "                listOf(",
    ]
    for entry in entries:
        lines.extend(_entry_lines(entry))
    lines.extend(["                ),", "        )", "}"])
    return "\n".join(lines) + "\n"


DEFAULT_DIR_RELATIVE = Path(
    "external-assets/Juego Completo/Formato Americano 57x88 mm/AF Enfrentamientos"
)
DEFAULT_OUT_RELATIVE = Path(
    "core/src/commonMain/kotlin/io/kdmtracker/core/content/generated/Core15Monsters.kt"
)


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _find(directory: Path, prefix: str) -> Path:
    matches = [p for p in directory.glob(f"{prefix}*.pdf") if "Acci" not in p.name]
    if not matches:
        raise SystemExit(f"no {prefix} deck found in {directory}")
    return matches[0]


def main(argv: Optional[Sequence[str]] = None) -> int:
    repo_root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--dir", type=Path, default=repo_root / DEFAULT_DIR_RELATIVE)
    parser.add_argument("--out", type=Path, default=repo_root / DEFAULT_OUT_RELATIVE)
    args = parser.parse_args(argv)

    if not args.dir.is_dir():
        parser.error(f"monster decks dir not found: {args.dir}")

    entries: List[Entry] = []
    for folder, monster in FOLDERS.items():
        directory = args.dir / folder
        if not directory.is_dir():
            raise SystemExit(f"missing monster folder: {directory}")
        entries += parse_ai_deck(_find(directory, "AF AI"), monster=monster)
        entries += parse_hit_locations(_find(directory, "AF HL"), monster=monster)

    cards = dedupe_sorted(entries, "monster cards")
    output = emit_kotlin(cards)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(output, encoding="utf-8")
    print(f"parsed {len(cards)} monster cards -> {args.out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
