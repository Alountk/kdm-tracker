#!/usr/bin/env python3
"""Parse the 1.5 innovation cards and emit committed Kotlin.

Reads the untracked ``AF Innovaciones.pdf`` (see ``external-assets/``), extracts
one innovation per PDF page, resolves the consequence graph (each card whose
sub-line says ``consecuencia[s] de[l] <parent>`` becomes a child of ``<parent>``),
and writes a deterministic ``Core15Innovations.kt``.

Design notes
------------
* The PDF renders exactly one card per page, so card boundaries need no guessing:
  a page is a card when its second non-blank line is a sub-line (tag /
  ``Innovación inicial`` / ``principio de …``). This is the parser's load-bearing
  assumption; ``pdfinfo`` page count is checked against the page split.
* The graph is built from the sub-lines, never from the ``Añade las
  consecuencias …`` prose. That prose only confirms a card *has* consequences, so
  it is stripped from the description and used solely as a cross-check.
* Determinism: no timestamps, no paths, entries and consequence lists sorted by
  name, stable escaping.
"""

from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional, Sequence

sys.path.insert(0, str(Path(__file__).resolve().parent))

from kotlin_emit import description_lines, indent, kotlin_escape, normalize_ws  # noqa: E402
from pdf_text import pdf_info, pdf_text  # noqa: E402

SURVIVAL_LIMIT_RE = re.compile(r"^Límite de Supervivencia \+(\d+)$")
PARENT_RE = re.compile(r"consecuencias?\s+de(?:l)?\s+(.+?)\s*\.?\s*$", re.IGNORECASE)
# Anchor to the real footer. The deck prints it either as "Añade las consecuencias …"
# or, on at least one card (Amoníaco), as "Añade consecuencias …". A bare `^añade\b`
# silently truncates any effect line that merely starts with "Añade", so the anchor
# requires the word "consecuencias".
DECK_PROSE_RE = re.compile(r"^añade\s+(?:las\s+)?consecuencias\b", re.IGNORECASE)
SUBLINE_RE = re.compile(
    r"^(?:innovación inicial|principio de .+|consecuencias? de(?:l)? .+|[a-záéíóúüñ]+(?:,\s.*)?)$",
    re.IGNORECASE,
)
DECK_TITLE_PAGE = 1  # 1-based; the first page is the deck's title, not a card.

FORM_FEED = "\f"

_NAME_INDENT = 24
_CONS_STRING_INDENT = 32

GENERATED_HEADER = "// Generated by tools/content-ingest/ingest_innovations.py. Do not edit by hand."


@dataclass
class Card:
    name: str
    subline: str
    parent: Optional[str]
    description: str
    survival_limit_bonus: int = 0
    consequences: List[str] = field(default_factory=list)
    has_deck_prose: bool = False


def is_card_page(lines: Sequence[str]) -> bool:
    """"A card page is one with a body and a recognizable sub-line as line 2."""
    return len(lines) >= 3 and bool(SUBLINE_RE.match(lines[1]))


def extract_parent(subline: str) -> Optional[str]:
    match = PARENT_RE.search(subline)
    if match is None:
        return None
    return normalize_ws(match.group(1)).lower()


def parse_cards(text: str) -> List[Card]:
    pages = [page for page in text.split(FORM_FEED) if page.strip()]
    cards: List[Card] = []
    survival_limit_matches = 0

    for page_number, page in enumerate(pages, start=1):
        lines = [line.strip() for line in page.splitlines() if line.strip()]
        if not is_card_page(lines):
            if page_number == DECK_TITLE_PAGE:
                continue
            raise SystemExit(
                f"page {page_number} is neither the deck title nor a recognized card "
                f"(first lines: {lines[:2]!r}); refusing to silently drop it"
            )

        name, subline = lines[0], lines[1]
        body = lines[2:]

        has_deck_prose = False
        truncated: List[str] = []
        for line in body:
            if DECK_PROSE_RE.match(line):
                has_deck_prose = True
                break
            truncated.append(line)

        bonus = 0
        effect_lines: List[str] = []
        for line in truncated:
            limit = SURVIVAL_LIMIT_RE.match(line)
            if limit is not None:
                bonus = int(limit.group(1))
                survival_limit_matches += 1
            else:
                effect_lines.append(line)

        cards.append(
            Card(
                name=name,
                subline=subline,
                parent=extract_parent(subline),
                description=normalize_ws(" ".join(effect_lines)),
                survival_limit_bonus=bonus,
                has_deck_prose=has_deck_prose,
            )
        )

    expected_cards = len(pages) - 1  # one deck title page
    if len(cards) != expected_cards:
        raise SystemExit(
            f"parsed {len(cards)} cards from {len(pages)} pages but expected {expected_cards}; "
            "a card was dropped or a non-card page was parsed"
        )

    # I4: every card must carry the fields the emitted Kotlin requires.
    for card in cards:
        if not card.name or not card.description:
            raise SystemExit(
                f"card {card.name!r} has an empty name or description; refusing to emit a blank card"
            )

    # I2: the survival-limit cross-check. Each `Límite de Supervivencia +N` line becomes
    # exactly one non-zero bonus, and no such line may leak into a description.
    with_bonus = sum(1 for card in cards if card.survival_limit_bonus != 0)
    if survival_limit_matches != with_bonus:
        raise SystemExit(
            f"survival-limit mismatch: found {survival_limit_matches} "
            f"'Límite de Supervivencia +N' lines but {with_bonus} cards carry a non-zero bonus"
        )
    leaked = [card.name for card in cards if "Límite de Supervivencia" in card.description]
    if leaked:
        raise SystemExit(
            f"survival-limit text leaked into the description of {leaked}; refusing to emit"
        )

    return cards


def resolve_consequences(cards: List[Card]) -> List[Card]:
    by_normalized_name = {normalize_ws(card.name).lower(): card.name for card in cards}

    for card in cards:
        if card.parent is not None and card.parent not in by_normalized_name:
            raise SystemExit(f"card {card.name!r} references unknown parent {card.parent!r}")

    children = {card.name: [] for card in cards}
    for card in cards:
        if card.parent is not None:
            children[by_normalized_name[card.parent]].append(card.name)

    for card in cards:
        card.consequences = sorted(children[card.name])

    child_names = {card.name for card in cards if card.consequences}
    prose_names = {card.name for card in cards if card.has_deck_prose}
    if child_names != prose_names:
        raise SystemExit(
            "graph/prose mismatch: sub-line children "
            f"{sorted(child_names)} != deck-prose cards {sorted(prose_names)}"
        )

    cards.sort(key=lambda card: card.name)
    return cards


def _consequence_lines(consequences: Sequence[str]) -> List[str]:
    if not consequences:
        return [f'{indent(_NAME_INDENT)}consequences = emptyList(),']
    lines = [f"{indent(_NAME_INDENT)}consequences =", f"{indent(28)}listOf("]
    lines.extend(f'{indent(_CONS_STRING_INDENT)}"{kotlin_escape(name)}",' for name in consequences)
    lines.append(f"{indent(28)}),")
    return lines


def emit_kotlin(cards: Sequence[Card]) -> str:
    lines = [
        GENERATED_HEADER,
        "package io.kdmtracker.core.content.generated",
        "",
        "import io.kdmtracker.core.content.ContentBundle",
        "import io.kdmtracker.core.domain.Innovation",
        "",
        "object Core15Innovations {",
        "    val bundle: ContentBundle =",
        "        ContentBundle(",
        "            innovations =",
        "                listOf(",
    ]
    for card in cards:
        lines.append("                    Innovation(")
        lines.append(f'{indent(_NAME_INDENT)}name = "{kotlin_escape(card.name)}",')
        lines.extend(description_lines(card.description))
        lines.extend(_consequence_lines(card.consequences))
        lines.append(f"{indent(_NAME_INDENT)}survivalLimitBonus = {card.survival_limit_bonus},")
        lines.append("                    ),")
    lines.extend(
        [
            "                ),",
            "        )",
            "}",
        ]
    )
    return "\n".join(lines) + "\n"


DEFAULT_PDF_RELATIVE = Path("external-assets/Juego Completo/Formato Americano 57x88 mm/AF Innovaciones.pdf")
DEFAULT_OUT_RELATIVE = Path("core/src/commonMain/kotlin/io/kdmtracker/core/content/generated/Core15Innovations.kt")


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def main(argv: Optional[Sequence[str]] = None) -> int:
    repo_root = _repo_root()
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--pdf", type=Path, default=repo_root / DEFAULT_PDF_RELATIVE, help="path to AF Innovaciones.pdf")
    parser.add_argument("--out", type=Path, default=repo_root / DEFAULT_OUT_RELATIVE, help="output Kotlin file")
    args = parser.parse_args(argv)

    if not args.pdf.is_file():
        parser.error(f"PDF not found: {args.pdf}\nPass --pdf <path> (external-assets/ is untracked).")

    text = pdf_text(args.pdf)
    declared_pages = pdf_info(args.pdf).get("Pages")
    pages = [page for page in text.split(FORM_FEED) if page.strip()]
    if declared_pages is not None and int(declared_pages) != len(pages):
        raise SystemExit(f"page split mismatch: pdfinfo says {declared_pages}, split found {len(pages)}")

    cards = resolve_consequences(parse_cards(text))
    output = emit_kotlin(cards)

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(output, encoding="utf-8")

    with_bonus = sum(1 for card in cards if card.survival_limit_bonus)
    with_children = sum(1 for card in cards if card.consequences)
    print(
        f"parsed {len(cards)} cards from {len(pages)} pages "
        f"({with_bonus} with survival bonus, {with_children} with consequences) -> {args.out}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
